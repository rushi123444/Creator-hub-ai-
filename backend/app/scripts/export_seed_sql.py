"""Export seeded reference + demo data as PostgreSQL INSERT statements to stdout.

    python -m app.scripts.export_seed_sql > ../database/seed.sql

Seeds a throw-away in-memory SQLite database (never the configured one), then renders every row.
Demo accounts use the documented demo passwords; do NOT load this file into production.
"""
from __future__ import annotations

import json
import logging
import os
import sys
import uuid
from datetime import date, datetime, timezone

os.environ["DATABASE_URL"] = "sqlite://"
os.environ.setdefault("APP_ENV", "development")
os.environ.setdefault("BCRYPT_ROUNDS", "12")

from sqlalchemy import JSON, Boolean, Date, DateTime, Uuid  # noqa: E402
from sqlalchemy.orm import Session  # noqa: E402

import app.models  # noqa: E402,F401
from app.database.base import Base  # noqa: E402
from app.database.seed import seed_all  # noqa: E402
from app.database.session import make_engine  # noqa: E402


def literal(col, value) -> str:
    if value is None:
        return "NULL"
    t = col.type
    if isinstance(t, Boolean) or isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(t, JSON):
        return "'" + json.dumps(value, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    if isinstance(t, Uuid) or isinstance(value, uuid.UUID):
        return f"'{value}'::uuid"
    if isinstance(t, DateTime) or isinstance(value, datetime):
        if value.tzinfo is None:
            value = value.replace(tzinfo=timezone.utc)
        return f"'{value.astimezone(timezone.utc).isoformat()}'::timestamptz"
    if isinstance(t, Date) or isinstance(value, date):
        return f"'{value.isoformat()}'::date"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def render(session: Session) -> list[str]:
    lines = ["-- CreatorHub AI seed data (PostgreSQL). Generated by app.scripts.export_seed_sql.",
             "-- Demo accounts included: for local/demo databases only.", "BEGIN;",
             "SELECT set_config('app.current_role', 'system', true);"]
    for table in Base.metadata.sorted_tables:
        rows = session.execute(table.select()).mappings().all()
        if not rows:
            continue
        lines.append(f"\n-- {table.name} ({len(rows)} rows)")
        cols = [c.name for c in table.columns]
        collist = ", ".join(f'"{c}"' for c in cols)
        for row in rows:
            vals = ", ".join(literal(table.columns[c], row[c]) for c in cols)
            lines.append(f'INSERT INTO "{table.name}" ({collist}) VALUES ({vals}) ON CONFLICT DO NOTHING;')
        if any(c.autoincrement is True or (c.primary_key and c.type.python_type is int) for c in table.columns):
            pk = next((c for c in table.columns if c.primary_key and c.type.python_type is int), None)
            if pk is not None:
                lines.append(f"SELECT setval(pg_get_serial_sequence('{table.name}', '{pk.name}'), "
                             f'(SELECT COALESCE(MAX("{pk.name}"), 1) FROM "{table.name}"));')
    lines.append("COMMIT;")
    return lines


def main() -> int:
    logging.basicConfig(level=logging.WARNING, stream=sys.stderr)
    eng = make_engine("sqlite://")
    Base.metadata.create_all(eng)
    with Session(eng, expire_on_commit=False) as s:
        seed_all(s, include_demo_accounts=True)
        s.commit()
        lines = render(s)
    sys.stdout.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
