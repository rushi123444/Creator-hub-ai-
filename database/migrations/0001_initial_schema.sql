CREATE EXTENSION IF NOT EXISTS pgcrypto;   -- gen_random_uuid() (built in on PG13+, harmless otherwise)

-- ---------- generic updated_at trigger ---------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

